/**
 * @file
 *
 * The voter's proof that a ballot is well formed (include/ballot_proof.h), on
 * LaZer's linear proofs, stated over LaZer's own ring R_64 = Z_q[Y]/(Y^64 + 1),
 * q the 88-bit BGV modulus.
 *
 * R_q of degree N = 4096 is R_64[X]/(X^K - Y) with K = N / 64 = 64: an element
 * a is sum_r X^r a_r(Y), its piece a_r holding the coefficients a[r + K l]. A
 * vote for candidate j is X^(K j) = Y^j, which lives in piece 0 alone, so the
 * vote and the elements about it are single elements of R_64 rather than K of
 * them each, as lifting the statement from R_q would make them. With witness
 * w = (r_0..r_63, e1_0..e1_63, e2_0..e2_63, m, m', u'):
 *
 *   (a r)_k + 2 e1_k - u_k = 0				for k < K
 *   (b r)_k + 2 e2_k + [k = 0] m - v_k = 0	for k < K
 *   m - u' = 0
 *   Y^(64 - ncand) m - m' = 0
 *
 * with ||(r, e1, e2)|| <= B, m and m' binary and ||u'|| <= 1
 * (lazer/ballot.py). The first 2 K rows are (u, v) = (a r + 2 e1, b r + 2 e2
 * + m) in R_q, piece by piece, with the vote's other pieces zero because they
 * are not in the witness. A binary m equal to a u' of norm at most 1 is Y^j or
 * 0. The last row makes j a candidate: R_64 is negacyclic, so Y^(64 - ncand)
 * Y^j is Y^(64 - ncand + j), binary, for j < ncand, and -Y^(j - ncand), which
 * is not, for j >= ncand. A blank ballot, m = 0, is allowed, as before.
 *
 * Lifting the statement from R_q made m and m' 64 binary elements of R_64
 * each; this way the binary part is 2 elements, not 128, and the witness 195,
 * not 384. The parameters, generated by LaZer's lin-codegen.sage for a 114-bit
 * proof modulus, are in lazer/ballot.h.
 */

#include <stdlib.h>
#include <string.h>

#include "lazer.h"
#include "../lazer/ballot.h"
#include "ballot_proof.h"

#define N 		BALLOT_DEG
#define D 		64					/* LaZer's ring degree */
#define K 		BALLOT_STRIDE		/* N / D: pieces of an element of R_q */
#define ROWS 	(2 * K + 2)
#define COLS 	(3 * K + 3)
#define COL_M 	(3 * K)
#define COL_M2 	(3 * K + 1)
#define COL_U2 	(3 * K + 2)
#define PARAMS 	lvm_ballot

/* floor(B^2) for the bound on ||(r, e1, e2)||, B = 1.2 sqrt(3 * 4096 / 2) as
 * in lazer/ballot.py. */
#define L2_RE 	8847

static const uint8_t ppseed[32] = "lvm ballot proof, LaZer v1";

static __int128 modulus(void) {
	return BALLOT_Q;
}

static __int128 centre(__int128 x) {
	const __int128 q = modulus();

	x %= q;
	if (x > q / 2) {
		x -= q;
	} else if (x < -(q / 2)) {
		x += q;
	}
	return x;
}

/* An integer of LaZer's from a signed 128-bit value. */
static void set_i128(int_ptr x, __int128 v) {
	unsigned __int128 a = v < 0 ? -(unsigned __int128) v : (unsigned __int128) v;

	int_set_zero(x);
	x->limbs[0] = (limb_t) a;
	if (x->nlimbs > 1) {
		x->limbs[1] = (limb_t) (a >> 64);
	}
	x->neg = v < 0;
}

/* The statement, A w + t = 0 over R_64: entries of A and t as coefficient
 * arrays, centred mod q. */
typedef struct {
	__int128 *A, *t;
} stmt_t;

static __int128 *at(stmt_t *st, int row, int col) {
	return st->A + ((size_t) row * COLS + col) * D;
}

/* Coefficient l of piece k of an element of R_q. */
#define PIECE(x, k, l) 	((x)[(k) + K * (l)])

/* Rows row0 .. row0 + K - 1: multiplication by x, from the K pieces of r in
 * columns 0 .. K - 1, as the K x K matrix whose entry (k, t) is x_(k-t) for
 * t <= k and Y x_(k-t+K) for t > k: X^(i+t) is X^k Y when i + t wraps past K. */
static void mul_block(stmt_t *st, int row0, const __int128 x[]) {
	for (int k = 0; k < K; k++) {
		for (int t = 0; t < K; t++) {
			__int128 *e = at(st, row0 + k, t);

			if (t <= k) {
				for (int l = 0; l < D; l++) {
					e[l] = centre(PIECE(x, k - t, l));
				}
			} else {
				/* Y y: coefficient l is y's l - 1, and the top one wraps
				 * negated to the bottom */
				e[0] = centre(-PIECE(x, k - t + K, D - 1));
				for (int l = 1; l < D; l++) {
					e[l] = centre(PIECE(x, k - t + K, l - 1));
				}
			}
		}
	}
}

static void stmt_init(stmt_t *st, const __int128 u[], const __int128 v[],
		const __int128 a[], const __int128 b[], int ncand) {
	st->A = calloc((size_t) ROWS * COLS * D, sizeof(__int128));
	st->t = calloc((size_t) ROWS * D, sizeof(__int128));
	mul_block(st, 0, a);							/* a r + 2 e1 - u */
	mul_block(st, K, b);							/* b r + 2 e2 + m - v */
	for (int k = 0; k < K; k++) {
		at(st, k, K + k)[0] = 2;
		at(st, K + k, 2 * K + k)[0] = 2;
		for (int l = 0; l < D; l++) {
			st->t[(size_t) k * D + l] = centre(-PIECE(u, k, l));
			st->t[(size_t) (K + k) * D + l] = centre(-PIECE(v, k, l));
		}
	}
	at(st, K, COL_M)[0] = 1;
	at(st, 2 * K, COL_M)[0] = 1;					/* m - u' */
	at(st, 2 * K, COL_U2)[0] = -1;
	at(st, 2 * K + 1, COL_M)[D - ncand] = 1;		/* Y^(D - ncand) m - m' */
	at(st, 2 * K + 1, COL_M2)[0] = -1;
}

static void stmt_clear(stmt_t *st) {
	free(st->A);
	free(st->t);
}

/* LaZer's polynomials from coefficient arrays. */
static void set_polymat(polymat_t A, stmt_t *st) {
	for (int i = 0; i < ROWS; i++) {
		for (int j = 0; j < COLS; j++) {
			poly_ptr p = polymat_get_elem(A, i, j);
			const __int128 *c = at(st, i, j);

			for (int k = 0; k < D; k++) {
				set_i128(poly_get_coeff(p, k), c[k]);
			}
		}
	}
}

static void set_polyvec(polyvec_t t, const __int128 *c, unsigned n) {
	for (unsigned i = 0; i < n; i++) {
		poly_ptr p = polyvec_get_elem(t, i);

		for (int k = 0; k < D; k++) {
			set_i128(poly_get_coeff(p, k), c[(size_t) i * D + k]);
		}
	}
}

/* Whether c = x s + 2 e + m in Z_q[X]/(X^N + 1), s ternary. */
static int row_holds(const __int128 c[], const __int128 x[], const int64_t s[],
		const int64_t e[], const int64_t m[]) {
	const __int128 q = modulus();
	__int128 *acc = calloc(N, sizeof(__int128));
	int ok = 1;

	for (int i = 0; i < N; i++) {
		if (s[i] == 0) {
			continue;
		}
		for (int j = 0; j < N; j++) {
			__int128 y = x[j] * s[i];
			if (i + j < N) {
				acc[i + j] += y;
			} else {
				acc[i + j - N] -= y;
			}
		}
	}
	for (int i = 0; i < N && ok; i++) {
		ok = (acc[i] + 2 * e[i] + (m != NULL ? m[i] : 0) - c[i]) % q == 0;
	}
	free(acc);
	return ok;
}

/* Whether (r, e1, e2, m) is a witness of the form the proof needs, a vote
 * X^(K j) for one of the first ncand candidates, or none. */
static int witness_ok(const int64_t r[], const int64_t e1[], const int64_t e2[],
		const int64_t m[], int ncand) {
	int64_t l2 = 0, ones = 0;

	for (int i = 0; i < N; i++) {
		if (r[i] < -1 || r[i] > 1 || e1[i] < -1 || e1[i] > 1 || e2[i] < -1
				|| e2[i] > 1 || m[i] < 0 || m[i] > 1) {
			return 0;
		}
		l2 += r[i] * r[i] + e1[i] * e1[i] + e2[i] * e2[i];
		ones += m[i];
		if (m[i] != 0 && (i % K != 0 || i / K >= ncand)) {
			return 0;
		}
	}
	return l2 <= L2_RE && ones <= 1;
}

void ballot_setup(void) {
	lazer_init();
}

size_t ballot_proof_len(void) {
	return lin_params_get_prooflen(PARAMS);
}

int ballot_prove(uint8_t *proof, size_t *len, const __int128 u[],
		const __int128 v[], const __int128 a[], const __int128 b[],
		const int64_t r[], const int64_t e1[], const int64_t e2[],
		const int64_t m[], int ncand, const uint8_t *ctx, size_t ctxlen) {
	lin_prover_state_t P;
	polymat_t A;
	polyvec_t t, w;
	stmt_t st;
	int64_t *wv;
	INT_T(q, 2);

	/* LaZer's prover does not check its statement, and on a false one its
	 * responses leave the range the encoding is sized for and overrun the
	 * proof buffer. */
	if (ncand < 1 || ncand > BALLOT_MAXCAND || !witness_ok(r, e1, e2, m, ncand)
			|| !row_holds(u, a, r, e1, NULL)
			|| !row_holds(v, b, r, e2, m)) {
		return 0;
	}
	set_i128(q, modulus());
	POLYRING_T(Rq, q, D);
	stmt_init(&st, u, v, a, b, ncand);
	wv = calloc((size_t) COLS * D, sizeof(int64_t));
	for (int k = 0; k < K; k++) {
		for (int l = 0; l < D; l++) {
			wv[(size_t) k * D + l] = PIECE(r, k, l);
			wv[(size_t) (K + k) * D + l] = PIECE(e1, k, l);
			wv[(size_t) (2 * K + k) * D + l] = PIECE(e2, k, l);
		}
	}
	for (int l = 0; l < D; l++) {
		wv[COL_M * D + l] = PIECE(m, 0, l);
		wv[COL_U2 * D + l] = PIECE(m, 0, l);		/* u' = m */
	}
	for (int j = 0; j < ncand; j++) {				/* m' = Y^(D - ncand) m */
		wv[COL_M2 * D + D - ncand + j] = PIECE(m, 0, j);
	}
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	polyvec_alloc(w, Rq, COLS);
	set_polymat(A, &st);
	set_polyvec(t, st.t, ROWS);
	polyvec_set_coeffvec_i64(w, wv);

	*len = ballot_proof_len();
	lin_prover_init(P, ppseed, PARAMS);
	lin_prover_set_statement(P, A, t);
	lin_prover_set_witness(P, w);
	lin_prover_prove_ctx(P, proof, len, NULL, ctx, ctxlen);
	lin_prover_clear(P);

	polymat_free(A);
	polyvec_free(t);
	polyvec_free(w);
	free(wv);
	stmt_clear(&st);
	return 1;
}

int ballot_verify(const uint8_t *proof, size_t len, const __int128 u[],
		const __int128 v[], const __int128 a[], const __int128 b[], int ncand,
		const uint8_t *ctx, size_t ctxlen) {
	lin_verifier_state_t V;
	polymat_t A;
	polyvec_t t;
	stmt_t st;
	size_t used = len;
	int ok;
	INT_T(q, 2);

	/* The encoding's length varies; ballot_proof_len() bounds it. */
	if (len == 0 || len > ballot_proof_len() || ncand < 1
			|| ncand > BALLOT_MAXCAND) {
		return 0;
	}
	set_i128(q, modulus());
	POLYRING_T(Rq, q, D);
	stmt_init(&st, u, v, a, b, ncand);
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	set_polymat(A, &st);
	set_polyvec(t, st.t, ROWS);

	lin_verifier_init(V, ppseed, PARAMS);
	lin_verifier_set_statement(V, A, t);
	ok = lin_verifier_verify_ctx(V, proof, &used, ctx, ctxlen) && used == len;
	lin_verifier_clear(V);

	polymat_free(A);
	polyvec_free(t);
	stmt_clear(&st);
	return ok;
}
